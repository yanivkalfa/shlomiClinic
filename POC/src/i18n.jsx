const LangCtx = createContext(null);

export function LangProvider({ children }) {
  const [lang, setLang] = useState('en');
  const isRTL = lang === 'he';
  const idx = isRTL ? 1 : 0;

  const t = useCallback((key, params) => {
    const entry = DICT[key];
    let s = entry ? entry[idx] : key;
    if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  }, [idx]);

  // Bilingual data values: ['English', 'עברית'] arrays resolved by current language
  const L = useCallback((v) => (Array.isArray(v) ? v[idx] ?? v[0] : v), [idx]);

  const locale = isRTL ? 'he-IL' : 'en-GB';
  const fmtMoney = useCallback((n) => new Intl.NumberFormat(locale, { style: 'currency', currency: 'ILS', maximumFractionDigits: 0 }).format(n), [locale]);
  const fmtNum = useCallback((n) => new Intl.NumberFormat(locale).format(n), [locale]);
  const fmtDate = useCallback((d) => new Intl.DateTimeFormat(locale, { day: '2-digit', month: '2-digit', year: 'numeric' }).format(new Date(d)), [locale]);
  const fmtDateLong = useCallback((d) => new Intl.DateTimeFormat(locale, { weekday: 'long', day: 'numeric', month: 'long', year: 'numeric' }).format(new Date(d)), [locale]);
  const fmtTime = useCallback((d) => new Intl.DateTimeFormat(locale, { hour: '2-digit', minute: '2-digit', hourCycle: 'h23' }).format(new Date(d)), [locale]);
  const fmtMonth = useCallback((d) => new Intl.DateTimeFormat(locale, { month: 'short' }).format(new Date(d)), [locale]);

  const value = useMemo(() => ({ lang, setLang, isRTL, t, L, locale, fmtMoney, fmtNum, fmtDate, fmtDateLong, fmtTime, fmtMonth }),
    [lang, isRTL, t, L, locale, fmtMoney, fmtNum, fmtDate, fmtDateLong, fmtTime, fmtMonth]);

  return <LangCtx.Provider value={value}>{children}</LangCtx.Provider>;
}

export function useLang() {
  return useContext(LangCtx);
}
